// Writes ../gemcore.gen.ts: the GemCore sprites, sounds and font these pieces use, as paths inside media/ (the link
// to a GemCore checkout, tools/link-gemcore.sh). GemCore names each sprite frame by a GUID in its .yy, so the paths
// are read from there, in frame order. Run again after GemCore's sprites change:
//
//   bun content/gemcore/tools/gen-assets.ts
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const media = join(root, "media");
if (!existsSync(join(media, "RookTKOs GemCore.yyp"))) throw new Error("media/ isn't a GemCore checkout: run tools/link-gemcore.sh first");

const SPRITES = [
  "spr_logo_gemcore", "spr_logo_rooktko",
  "spr_player_probe", "spr_player_ship0", "spr_player_ship3", "spr_8drill_ship", "bigdrill",
  "spr_ship_destroyed", "spr_coreFace", "spr_core_center",
  "spr_gem_diamond_large", "spr_gem_ruby_large", "spr_gem_opal_large", "spr_gem_emerald_large",
];
const SOUNDS = {
  theme: "track_mainmenu/track_mainMenu.wav",
  judgement: "track_judgement_day/track_judgement_day.wav",
  gameover: "track_gameover/track_gameover.wav",
  radio: "snd_radio_filter_1/snd_radio_filter_1.mp3",
  radar: "snd_radar_alert/snd_radar_alert.wav",
  glass: "snd_glassbreak1/snd_glassBreak1.wav",
  impact: "snd_explosion_mainimpact/snd_explosion_mainImpact.wav",
} as const;
const FONT = "static/font/Corp Console.ttf";

type Sprite = { w: number; h: number; frames: string[] };
const sprites: Record<string, Sprite> = {};
for (const name of SPRITES) {
  const yy = readFileSync(join(media, "sprites", name, `${name}.yy`), "utf8");
  // the frames list sits before the sequence; each frame's GUID is its png's name
  const list = yy.slice(yy.indexOf('"frames":['), yy.indexOf('"gridX"'));
  const frames = [...list.matchAll(/"name":"([0-9a-f-]{36})","resourceType":"GMSpriteFrame"/g)].map((m) => `sprites/${name}/${m[1]}.png`);
  // the sprite's own size: the top-level keys, two spaces in (layers and the sequence nest deeper)
  const w = Number(/^  "width":(\d+),/m.exec(yy)?.[1]);
  const h = Number(/^  "height":(\d+),/m.exec(yy)?.[1]);
  if (!frames.length || !w || !h) throw new Error(`${name}: no frames or size in its .yy`);
  for (const f of frames) if (!existsSync(join(media, f))) throw new Error(`${name}: ${f} is missing`);
  sprites[name] = { w, h, frames };
}
for (const p of [...Object.values(SOUNDS), FONT]) {
  const at = p === FONT ? p : `sounds/${p}`;
  if (!existsSync(join(media, at))) throw new Error(`${at} is missing`);
}

const out = `// Generated by tools/gen-assets.ts from the linked GemCore checkout; don't edit by hand.
// Paths are inside media/ (staticFile's folder), which links to GemCore: no GemCore file is copied into this repo.
export const SPRITES = ${JSON.stringify(sprites, null, 2)} as const;

export const SOUNDS = ${JSON.stringify(Object.fromEntries(Object.entries(SOUNDS).map(([k, v]) => [k, `sounds/${v}`])), null, 2)} as const;

export const FONT_FILE = ${JSON.stringify(FONT)};
`;
writeFileSync(join(root, "gemcore.gen.ts"), out);
console.log(`gemcore.gen.ts: ${SPRITES.length} sprites, ${Object.keys(SOUNDS).length} sounds, 1 font`);
